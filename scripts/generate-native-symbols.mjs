#!/usr/bin/env node
/*
 * generate-native-symbols.mjs - The native debugger's Apple II symbols, from the browser's
 *
 * src/js/debug/symbols.js is the authority: the names the browser's debugger
 * puts on zero page locations, soft switches, the disk controller, the ROM
 * entry points and Applesoft's workspace. The native debugger needs the same
 * names, and a second hand-kept table would drift from the first with nothing
 * to catch it, so the C++ table is generated from the JS one and checked in.
 *
 * Usage:
 *   node scripts/generate-native-symbols.mjs           # write the file
 *   node scripts/generate-native-symbols.mjs --check   # verify it is current
 *
 * Written by
 *  Mike Daley <michael_daley@icloud.com>
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(ROOT, "src/js/debug/symbols.js");
const OUTPUT = resolve(ROOT, "native/src/debugger/apple2_symbols.inc");

const { ALL_SYMBOLS } = await import(pathToFileURL(SOURCE).href);

// A C string literal: the descriptions are plain ASCII, but escape anyway.
const literal = (text) =>
  `"${String(text).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

const rows = Object.entries(ALL_SYMBOLS)
  .map(([address, info]) => [Number(address), info])
  .sort((a, b) => a[0] - b[0])
  .map(
    ([address, info]) =>
      `    {0x${address.toString(16).toUpperCase().padStart(4, "0")}, ${literal(info.name)}, ` +
      `${literal(info.desc)}, ${literal(info.category)}},`,
  );

const text = `// Generated by scripts/generate-native-symbols.mjs from src/js/debug/symbols.js.
// Do not edit: change the JS table and run \`npm run generate:native-symbols\`.
// One row per address, sorted: address, name, description, category.
${rows.join("\n")}
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  if (current !== text) {
    console.error(
      "native/src/debugger/apple2_symbols.inc is out of date with src/js/debug/symbols.js.\n" +
        "Run: npm run generate:native-symbols",
    );
    process.exit(1);
  }
  console.log(`native symbols are current (${rows.length} entries)`);
} else {
  writeFileSync(OUTPUT, text);
  console.log(`wrote ${rows.length} symbols to native/src/debugger/apple2_symbols.inc`);
}
