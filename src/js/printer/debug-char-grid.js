/*
 * debug-char-grid.js - TEMPORARY: visualize ImageWriter II draft-quality
 * column-byte character data as a 12×9 dot grid for manual verification
 * against Appendix C of the ImageWriter II Technical Reference Manual.
 *
 * Delete this file once character ROM data is verified.
 *
 * Format: 12 bytes per character, one per column (left to right)
 *   bit 0 = wire 1 (top row)
 *   bit 7 = wire 8 (bottom row of normal chars)
 *   col 11 = trailing blank spacer (should always be 0x00)
 *
 * Usage (browser console):
 *   import { showGrid, showGrids } from './debug-char-grid.js';
 *   showGrid(0x21, [0x00,0x00,0x00,0x00,0xBF,0x00,0xBF,0x00,0x00,0x00,0x00,0x00]);
 *   showGrids(DRAFT_ROM);
 */

export function showGrid(charCode, cols) {
  const hex    = `$${charCode.toString(16).toUpperCase().padStart(2, '0')}`;
  const chr    = charCode >= 0x20 && charCode < 0x7F ? ` '${String.fromCharCode(charCode)}'` : '';
  const bytes  = cols.map(b => `0x${b.toString(16).padStart(2, '0')}`).join(', ');
  const LEFT_W = 39; // ' 1|' (3) + 12 cols × 3 chars (36)
  const GAP    = '       '; // 7 spaces between boxes

  let hdr = '   ';
  for (let col = 1; col <= 12; col++) hdr += ` ${col % 10} `;

  let out = `\n${charCode}/${hex}${chr}  [${bytes}]\n`;
  out += hdr.trimEnd().padEnd(LEFT_W) + GAP + ' 123456789012\n';
  out += ('    ' + '-'.repeat(35)).padEnd(LEFT_W) + GAP + ' ------------\n';

  for (let row = 0; row < 9; row++) {
    let left  = `${(row + 1).toString().padStart(2, ' ')}|`;
    let right = '';
    for (let col = 0; col < 12; col++) {
      const set = (cols[col] >> row & 1);
      left  += ` ${set ? '●' : '.'} `;
      right += set ? '●' : ' ';
    }
    out += left.padEnd(LEFT_W) + GAP + '|' + right.trimEnd() + '\n';
  }
  console.log(out);
}

export function showGrids(rom) {
  for (const [code, cols] of Object.entries(rom)) {
    showGrid(Number(code), cols);
  }
}

